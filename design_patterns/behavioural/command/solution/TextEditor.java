package design_patterns.behavioural.command.solution;

public class TextEditor {
    public void boldText() {
        System.out.println("Text is in Bold");
    }

    public void unboldText() {
        System.out.println("Bold removed");
    }

    public void italicText() {
        System.out.println("Text is in Italic");
    }

    public void unItalicText() {
        System.out.println("Italic removed");
    }

    public void underlineText() {
        System.out.println("Text is Underlined");
    }
}
